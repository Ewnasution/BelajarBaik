// Maintenance-only generator. The committed snapshot is used at runtime on all
// devices; normal builds never regenerate it from the host's ICU version.
import { writeFileSync } from 'node:fs';
const format = new Intl.DateTimeFormat('en', { calendar: 'islamic-umalqura', numberingSystem: 'latn', timeZone: 'UTC', year: 'numeric', month: 'numeric', day: 'numeric' });
if (format.resolvedOptions().calendar !== 'islamic-umalqura') throw new Error('Umm al-Qura ICU data required');
const starts = [];
let firstYear, firstMonth;
for (let day = Date.UTC(1898, 0, 1) / 86400000; day <= Date.UTC(2203, 0, 1) / 86400000; day++) {
  const parts = Object.fromEntries(format.formatToParts(new Date(day * 86400000)).map(p => [p.type, p.value]));
  if (Number(parts.day) !== 1) continue;
  if (!starts.length) { firstYear = Number(parts.year); firstMonth = Number(parts.month); }
  starts.push(day);
}
const lengths = starts.slice(1).map((start, i) => start - starts[i]);
if (lengths.some(n => n !== 29 && n !== 30)) throw new Error('Unexpected month length');
writeFileSync('src/data/hijri-calendar.js', `// Pinned ICU ${process.versions.icu} islamic-umalqura snapshot. Generated by scripts/generate-hijri-calendar.js.\n// Includes padding around the supported input range 1900–2200; outside ICU's\n// observational table, dates follow its Umm al-Qura approximation.\nexport const FIRST_YEAR = ${firstYear};\nexport const FIRST_MONTH = ${firstMonth};\nexport const FIRST_DAY = ${starts[0]};\nexport const MONTH_LENGTHS = '${lengths.map(n => n - 29).join('')}';\n`);
